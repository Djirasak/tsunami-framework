// Regenerate icon data from Lucide release zips (unzipped):
//   lucide-font-X.Y.Z.zip  -> <font-dir>  (lucide.woff2, codepoints.json)
//   lucide-icons-X.Y.Z.zip -> <icons-dir> (per-icon .json with tags)
// Usage: bun scripts/lucide.ts <font-dir> <icons-dir> <version>
// Writes fonts/lucide.woff2, src/icons/_lucide.scss (name -> codepoint) and site/public/docs/icons.json (search index).
const [fontDir, iconsDir, version] = process.argv.slice(2);
if (!fontDir || !iconsDir || !version)
  throw new Error(
    "usage: bun scripts/lucide.ts <font-dir> <icons-dir> <version>",
  );

const root = new URL("..", import.meta.url).pathname;
const codepoints: Record<string, number> = await Bun.file(
  `${fontDir}/codepoints.json`,
).json();
const names = Object.keys(codepoints).sort();

// Tags live on the canonical icon; aliases share its codepoint.
const tagsByCode = new Map<number, string>();
for (const name of names) {
  const meta = Bun.file(`${iconsDir}/${name}.json`);
  if (await meta.exists())
    tagsByCode.set(
      codepoints[name],
      [name, ...((await meta.json()).tags ?? [])].join(" "),
    );
}

const entries: string[] = [];
const index: [string, string][] = [];
for (const name of names) {
  if (!/^[a-z][a-z0-9-]*$/.test(name))
    throw new Error(`unexpected icon name: ${name}`);
  entries.push(`  "${name}": "${codepoints[name].toString(16)}",`);
  index.push([name, tagsByCode.get(codepoints[name]) ?? ""]);
}

await Bun.write(
  `${root}fonts/lucide.woff2`,
  Bun.file(`${fontDir}/lucide.woff2`),
);
await Bun.write(
  `${root}src/icons/_lucide.scss`,
  `// Generated by scripts/lucide.ts from Lucide ${version} (ISC, see fonts/Lucide-LICENSE.txt). Do not edit.
// Icon name -> codepoint (hex) in fonts/lucide.woff2. Aliases share a codepoint.
$icons: (
${entries.join("\n")}
);
`,
);
await Bun.write(
  `${root}site/public/docs/icons.json`,
  JSON.stringify({ version, icons: index }),
);
console.log(
  `${names.length} names, ${new Set(Object.values(codepoints)).size} glyphs from Lucide ${version}`,
);
