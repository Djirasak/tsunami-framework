// Regenerate flags from an unzipped flag-icons release (github.com/lipis/flag-icons).
// Usage: bun scripts/flags.ts <flag-icons-dir> <version>
// Copies flags/4x3/*.svg to flags/, writes src/icons/_flags.scss (codes) and site/public/docs/flags.json (search index).
const [dir, version] = process.argv.slice(2);
if (!dir || !version)
  throw new Error("usage: bun scripts/flags.ts <flag-icons-dir> <version>");

const root = new URL("..", import.meta.url).pathname;
const countries: { code: string; name: string }[] = await Bun.file(
  `${dir}/country.json`,
).json();
const names = new Map(countries.map((c) => [c.code, c.name]));
const codes = [...new Bun.Glob("*.svg").scanSync(`${dir}/flags/4x3`)]
  .map((f) => f.slice(0, -4))
  .sort();

for (const code of codes) {
  if (!/^[a-z]{2,}(-[a-z]+)?$/.test(code))
    throw new Error(`unexpected flag code: ${code}`);
  await Bun.write(
    `${root}flags/${code}.svg`,
    Bun.file(`${dir}/flags/4x3/${code}.svg`),
  );
}
await Bun.write(`${root}flags/LICENSE.txt`, Bun.file(`${dir}/LICENSE`));
await Bun.write(
  `${root}src/icons/_flags.scss`,
  `// Generated by scripts/flags.ts from flag-icons ${version} (MIT, see flags/LICENSE.txt). Do not edit.\n$codes: (${codes.join(", ")});\n`,
);
await Bun.write(
  `${root}site/public/docs/flags.json`,
  JSON.stringify({ version, flags: codes.map((c) => [c, names.get(c) ?? c]) }),
);
console.log(`${codes.length} flags from flag-icons ${version}`);
